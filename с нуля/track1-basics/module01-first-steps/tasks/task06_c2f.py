"""
Задача 06. Цельсий → Фаренгейт

Прочитайте температуру в градусах Цельсия (число может быть дробным)
и переведите её в градусы Фаренгейта по формуле:

    f = c * 9 / 5 + 32

Выведите одно число — результат, округлённый до одного знака после точки.

Пример
------
Ввод:
36.6
Вывод:
97.9
"""

c = float(input())
f = c * 9 / 5 + 32
print(round(f, 1))  
