"""
Задача 16. Сумма цифр трёхзначного числа

Прочитайте трёхзначное целое число и выведите сумму его цифр:

    Сумма цифр: <результат>

Цифры извлекайте арифметикой (// и %), не строковыми методами.

Пример
------
Ввод:
472
Вывод:
Сумма цифр: 13

Подсказка
---------
Сотни: n // 100, десятки: n // 10 % 10, единицы: n % 10.
"""

n = int(input())
hundreds = n // 100
tens = n // 10 % 10
units = n % 10
sum_of_digits = hundreds + tens + units
print(f"Сумма цифр: {sum_of_digits}")
