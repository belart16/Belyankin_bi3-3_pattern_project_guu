"""
Задача 17 ★. Палиндром из трёх цифр

Прочитайте трёхзначное целое число и выведите True, если оно одинаково
читается слева направо и справа налево, иначе False.

Число «разбирайте» только арифметикой (// и %): строки и срезы появятся
в следующих модулях.

Пример
------
Ввод:
121
Вывод:
True

Ввод:
123
Вывод:
False
"""


n = int(input())
first_digit = n // 100
last_digit = n % 10
print(first_digit == last_digit)
