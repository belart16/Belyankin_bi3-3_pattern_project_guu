"""
Задача 15. Банковский вклад

В банк положили сумму под p процентов годовых. Прочитайте три числа,
каждое с отдельной строки:

1. начальную сумму (может быть дробной);
2. процентную ставку p (целое);
3. срок в годах n (целое).

Считая, что проценты капитализируются раз в год, выведите итоговую сумму
через n лет, округлённую до 2 знаков:

    Итоговая сумма: <сумма * (1 + p/100) в степени n>

Пример
------
Ввод:
10000
7
5
Вывод:
Итоговая сумма: 14025.52
"""

initial_amount = float(input())
interest_rate = int(input())
years = int(input())

final_amount = initial_amount * (1 + interest_rate / 100) ** years
print(f"Итоговая сумма: {final_amount:.2f}")
