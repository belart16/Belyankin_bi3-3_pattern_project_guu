"""
Задача 02-08. Существует ли треугольник

Прочитайте три положительных числа — длины сторон. Выведите «да», если из
них можно составить треугольник (каждая сторона меньше суммы двух других),
иначе «нет».

Пример
------
Ввод:
3
4
5
Вывод:
да
"""

a = int(input())
b = int(input())
c = int(input())    

if a + b > c and a + c > b and b + c > a:
    print("да")
else:
    print("нет")
