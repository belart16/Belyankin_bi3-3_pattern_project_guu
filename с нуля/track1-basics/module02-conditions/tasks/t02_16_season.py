"""
Задача 02-16. Время года

Прочитайте порядковый номер месяца (целое число). Выведите время года:

- 12, 1, 2 — «зима»;
- 3, 4, 5 — «весна»;
- 6, 7, 8 — «лето»;
- 9, 10, 11 — «осень»;
- любой другой номер — «ошибка».

Пример
------
Ввод:
4
Вывод:
весна
"""

month = int(input())
if month in (12, 1, 2):
    print("зима")
elif month in (3, 4, 5):
    print("весна")
elif month in (6, 7, 8):
    print("лето")
elif month in (9, 10, 11):
    print("осень")
else:
    print("ошибка")

