"""
Задача 02-10. Корни квадратного уравнения

Прочитайте коэффициенты a, b, c квадратного уравнения ax² + bx + c = 0
(целые числа, a ≠ 0). Вычислите дискриминант D = b² − 4ac и выведите:

- «нет корней» — если D < 0;
- «один корень: X» — если D = 0 (X округлите до 3 знаков);
- «два корня: X Y» — если D > 0, корни по возрастанию, каждый округлите
  до 3 знаков.

Пример
------
Ввод:
1
-3
2
Вывод:
два корня: 1.0 2.0
"""

import math

a = int(input())
b = int(input())
c = int(input())

D = b ** 2 - 4 * a * c

if D < 0:
    print("нет корней")
elif D == 0:
    X = -b / (2 * a)
    print(f"один корень: {X:.3f}")
else:
    X1 = (-b + math.hypot(D)) / (2 * a)
    X2 = (-b - math.hypot(D)) / (2 * a)
    print(f"два корня: {min(X1, X2):.3f} {max(X1, X2):.3f}")
