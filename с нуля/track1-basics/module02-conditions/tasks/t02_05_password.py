"""
Задача 02-05. Проверка пароля

Прочитайте строку — пароль. Если он совпадает со строкой «python123»,
выведите «доступ разрешён», иначе — «доступ запрещён».

Пример
------
Ввод:
python123
Вывод:
доступ разрешён
"""

password = input()
if password == "python123":
    print("доступ разрешён")
else:
    print("доступ запрещён")

