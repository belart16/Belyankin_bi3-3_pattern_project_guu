"""
Задача 04-17 ★. Анаграммы

Прочитайте две строки и проверьте, являются ли они анаграммами друг друга
(одна получается из другой перестановкой букв) — без учёта регистра
и пробелов. Выведите True или False.

Пример
------
Ввод:
листок
столик
Вывод:
True

Подсказка
---------
sorted("ба") даёт ['а', 'б'] — список букв по порядку. Анаграммы
после сортировки совпадают.
"""

s1 = input().replace(" ", "").lower()
s2 = input().replace(" ", "").lower()
print(sorted(s1) == sorted(s2))

