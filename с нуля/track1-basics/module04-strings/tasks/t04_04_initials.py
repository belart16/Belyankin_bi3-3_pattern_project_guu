"""
Задача 04-04. Инициалы

Прочитайте строку «Фамилия Имя Отчество» (ровно три слова) и выведите
инициалы точками: «И.И.И.» (первые буквы каждого слова).

Пример
------
Ввод:
Иванов Иван Иванович
Вывод:
И.И.И.
"""

s = input().split()
initials = [word[0] for word in s]
print(".".join(initials) + ".")
