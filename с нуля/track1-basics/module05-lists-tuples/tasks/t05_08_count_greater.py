"""
Задача 05-08. Больше, чем k

Прочитайте строку с числами через пробел, затем отдельной строкой —
целое число k. Выведите, сколько элементов списка больше k.

Пример
------
Ввод:
4 8 15 16
10
Вывод:
2
"""

numbers = list(map(int, input().split()))
k = int(input())
count = 0
for num in numbers:
    if num > k:
        count += 1
print(count)
