"""
Задача 05-02. Сумма и количество

Прочитайте числа через пробел и выведите две строки:

    Сумма: <сумма чисел>
    Количество: <сколько чисел>

Функции sum и len в этой задаче не использовать — считайте циклом.

Пример
------
Ввод:
4 8 15 16
Вывод:
Сумма: 43
Количество: 4
"""

numbers = input().split()
total = 0
count = 0
for num in numbers:
    total += int(num)
    count += 1
print(f"Сумма: {total}")
print(f"Количество: {count}")
