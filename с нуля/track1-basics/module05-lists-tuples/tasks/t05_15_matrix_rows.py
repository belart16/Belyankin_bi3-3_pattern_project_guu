"""
Задача 05-15. Суммы строк матрицы

Прочитайте два целых числа n и m (каждое с отдельной строки), затем n строк
матрицы — по m целых чисел через пробел. Выведите сумму каждой строки —
по одному числу на строку.

Пример
------
Ввод:
2
3
1 2 3
4 5 6
Вывод:
6
15
"""

n = int(input())
m = int(input())
matrix = []
for _ in range(n):
    row = list(map(int, input().split()))
    matrix.append(row)

for row in matrix:
    print(sum(row))
