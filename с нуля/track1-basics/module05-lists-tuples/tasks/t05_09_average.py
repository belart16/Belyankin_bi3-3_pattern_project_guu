"""
Задача 05-09. Среднее арифметическое

Прочитайте числа через пробел (гарантируется хотя бы одно) и выведите
их среднее арифметическое, округлённое до 2 знаков.

Здесь можно пользоваться sum и len.

Пример
------
Ввод:
1 2 3 4
Вывод:
2.5
"""

numbers = list(map(int, input().split()))
average = round(sum(numbers) / len(numbers), 2)
print(average)
