"""
Задача 03-09. Перевёрнутое число

Прочитайте целое число n (n ≥ 1) и выведите его «задом наперёд»: 1234 → 4321.
Ведущие нули результата теряются: 107 → 701, 1000 → 1.

Собирайте новое число в цикле операциями % 10 и // 10 — без строк.

Пример
------
Ввод:
1234
Вывод:
4321
"""

n = int(input())
reversed_num = 0
while n > 0:
    reversed_num = reversed_num * 10 + n % 10
    n //= 10
print(reversed_num)
