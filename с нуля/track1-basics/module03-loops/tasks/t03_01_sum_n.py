"""
Задача 03-01. Сумма от 1 до N

Прочитайте целое число n (n ≥ 1) и выведите сумму всех чисел от 1 до n.

Сумму обязательно посчитайте циклом — формула n(n+1)/2 не засчитывается
(цель упражнения — цикл).

Пример
------
Ввод:
5
Вывод:
15
"""

n = int(input())

sum = 0
for i in range(1, n + 1):
    sum += i
print(sum)
