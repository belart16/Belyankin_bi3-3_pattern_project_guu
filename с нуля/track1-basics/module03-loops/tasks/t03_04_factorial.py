"""
Задача 03-04. Факториал

Прочитайте целое число n (0 ≤ n ≤ 15) и выведите n! — произведение всех
целых чисел от 1 до n. По определению 0! = 1.

Функцию math.factorial не использовать — считайте циклом.

Пример
------
Ввод:
5
Вывод:
120
"""

n = int(input())
factorial = 1
for i in range(1, n + 1):
    factorial *= i
print(factorial)
