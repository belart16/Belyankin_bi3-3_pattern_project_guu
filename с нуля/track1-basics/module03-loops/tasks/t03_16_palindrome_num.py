"""
Задача 03-16 ★. Число-палиндром

Прочитайте целое число n (n ≥ 0) и выведите True, если оно одинаково
читается в обе стороны, иначе False.

Число разбирать циклом (как в задаче 03-09) — строки не использовать.

Пример
------
Ввод:
12321
Вывод:
True
"""

n = int(input())
original = n
reversed_num = 0
while n > 0:
    reversed_num = reversed_num * 10 + n % 10
    n //= 10
print(reversed_num == original)
