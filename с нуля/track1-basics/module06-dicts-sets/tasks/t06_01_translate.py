"""
Задача 06-01. Мини-словарь

В программе уже задан словарь перевода. Прочитайте слово и выведите его
перевод; если слова в словаре нет — выведите «нет в словаре».

Пример
------
Ввод:
cat
Вывод:
кот
"""

DICTIONARY = {
    "cat": "кот",
    "dog": "собака",
    "house": "дом",
    "sun": "солнце",
}

word = input()
if word in DICTIONARY:
    print(DICTIONARY[word])
else:
    print("нет в словаре")

