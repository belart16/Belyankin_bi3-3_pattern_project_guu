"""
Задача 06-08. Какие цифры есть в строке

Прочитайте строку и выведите все различные цифры, которые в ней
встречаются, — по возрастанию, через пробел. Если цифр нет, ничего
не выводите.

Пример
------
Ввод:
a1b23c1
Вывод:
1 2 3
"""


text = input()
digits = set()
for char in text:
    if char.isdigit():
        digits.add(char)

if digits:
    print(" ".join(sorted(digits)))
